using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Uno.Compiler.API;
using Uno.Compiler.API.Domain.IL;
using Uno.IO;

namespace Uno.Compiler.Foreign.Swift
{
    // Emits the generated Swift sources, the per-type Objective-C bridge headers and
    // implementations, and the Swift bridging header.
    partial class ForeignSwiftPass
    {
        // Name of the Swift module, which determines the name of the generated `-Swift.h`
        // header. Xcode derives it from the target name, replacing characters that are not
        // valid in a module name with '_'. We make that explicit (and use the same name in
        // our generated imports) when the sanitized name differs from the project name.
        string _swiftModuleName;

        void EnsureSwiftModuleName()
        {
            if (_swiftModuleName != null)
                return;

            var projectName = Environment.GetString("project.name") ?? "App";
            _swiftModuleName = SanitizeModuleName(projectName);

            if (_swiftModuleName != projectName)
                Environment.Set("pbxproj.moduleName", _swiftModuleName);
        }

        static string SanitizeModuleName(string name)
        {
            var sb = new StringBuilder(name.Length);

            foreach (var c in name)
                sb.Append(char.IsLetterOrDigit(c) || c == '_' ? c : '_');

            return sb.Length > 0 ? sb.ToString() : "App";
        }

        //-----------------------------------------------------
        // Swift source

        // The method is emitted without any leading indentation, so it can be written into
        // the body of the generated class by WriteSwiftFile.
        string GenSwiftMethod(Function f, string body, List<string> annotations, bool usesThis)
        {
            using (var tw = new StringWriter())
            {
                using (var ftw = new TextFormatter(tw))
                {
                    foreach (var annotation in annotations)
                        ftw.WriteLine("@" + annotation);

                    ftw.BeginLine();
                    ftw.Write("@objc public static func " + EscapeIdentifier(MethodName(f)) + "(");
                    ftw.Write(string.Join(", ", SwiftParameters(f, usesThis)));
                    ftw.Write(")");

                    if (!f.ReturnType.IsVoid)
                        ftw.Write(" -> " + Types.Get(f.ReturnType).Swift);

                    ftw.EndLine();

                    ftw.Indent("{");
                    ftw.WriteLines(body);
                    ftw.Unindent("}");

                    return tw.ToString();
                }
            }
        }

        List<string> SwiftParameters(Function f, bool usesThis)
        {
            var parameters = new List<string>();

            if (usesThis)
                parameters.Add("_ " + EscapeIdentifier("_this") + ": " + Types.Get(f.DeclaringType).Swift);

            foreach (var p in f.Parameters)
                parameters.Add("_ " + EscapeIdentifier(p.UnoName) + ": " + Types.Get(p.Type).Swift);

            return parameters;
        }

        void WriteSwiftFile(SwiftFile file)
        {
            using (var tw = new StringWriter())
            {
                using (var ftw = new TextFormatter(tw))
                {
                    ftw.WriteLine("// Generated by the Uno compiler for " + file.Type.FullName + ".");
                    ftw.WriteLine("// Do not edit.");
                    ftw.Skip();
                    ftw.WriteLine("import Foundation");

                    foreach (var import in file.Imports.OrderBy(x => x))
                        ftw.WriteLine("import " + import);

                    ftw.Skip();
                    ftw.WriteLine("@objc(" + file.ClassName + ")");
                    ftw.WriteLine("public final class " + file.ClassName + ": NSObject");
                    ftw.Indent("{");

                    foreach (var method in file.Methods)
                    {
                        ftw.WriteLines(method);
                        ftw.Skip();
                    }

                    ftw.Unindent("}");
                }

                var relativePath = "Foreign/" + file.ClassName + ".swift";
                var directory = Path.Combine(Environment.GetOutputPath("sourceDirectory"), "Foreign");
                Disk.WriteAllText(Path.Combine(directory, file.ClassName + ".swift"), tw.ToString());
                Environment.Require("sourceFile", relativePath);
            }
        }

        //-----------------------------------------------------
        // Objective-C bridge

        // The bridge header is read both by the generated Objective-C++ (where it also pulls
        // in the Uno runtime and the module's Swift header) and by Swift through the
        // bridging header. uSwift.h provides the Uno wrapper protocols that are visible from
        // Swift, so each bridge header does not have to repeat them.
        void WriteBridgeHeader(SwiftFile file)
        {
            using (var tw = new StringWriter())
            {
                using (var ftw = new TextFormatter(tw))
                {
                    ftw.WriteLine("#pragma once");
                    ftw.Skip();
                    ftw.WriteLine("#include <uSwift.h>");
                    ftw.Skip();
                    ftw.WriteLine("#ifdef __cplusplus");
                    ftw.WriteLine("#import \"" + _swiftModuleName + "-Swift.h\"");
                    ftw.WriteLine("#endif");
                    ftw.Skip();
                    ftw.WriteLine("@interface " + file.BridgeClassName + " : NSObject");

                    foreach (var declaration in file.BridgeDeclarations)
                        ftw.WriteLine(declaration);

                    ftw.WriteLine("@end");
                }

                var path = Path.Combine(Environment.GetOutputPath("headerDirectory"), file.BridgeHeaderName);
                Disk.WriteAllText(path, tw.ToString());
                Environment.Require("headerFile", file.BridgeHeaderName);
            }
        }

        void WriteBridgeImplementation(SwiftFile file)
        {
            using (var tw = new StringWriter())
            {
                using (var ftw = new TextFormatter(tw))
                {
                    ftw.WriteLine("@implementation " + file.BridgeClassName);

                    foreach (var implementation in file.BridgeImplementations)
                    {
                        ftw.WriteLines(implementation);
                        ftw.Skip();
                    }

                    ftw.WriteLine("@end");
                }

                Helpers.SourceDeclaration(tw.ToString(), file.Type, file.Type.Source);
            }
        }

        //-----------------------------------------------------
        // Swift bridging header

        void WriteSwiftBridgingHeader()
        {
            if (_files.Count == 0)
                return;

            using (var tw = new StringWriter())
            {
                using (var ftw = new TextFormatter(tw))
                {
                    // No include guard: this file is only ever used as the bridging header,
                    // which is compiled as the main file (a guard here only warns).
                    ftw.WriteLine("#import <Foundation/Foundation.h>");

                    foreach (var file in _files.Values.Where(x => x.HasBridge).OrderBy(x => x.BridgeHeaderName))
                        ftw.WriteLine("#import \"" + file.BridgeHeaderName + "\"");
                }

                var path = Path.Combine(Environment.GetOutputPath("headerDirectory"), "uSwiftBridging.h");
                Disk.WriteAllText(path, tw.ToString());
                Environment.Require("headerFile", "uSwiftBridging.h");
            }

            // A bridging header is only supported for application targets. Framework
            // (LIBRARY) builds would have to expose the same declarations through a module
            // instead, which is not supported yet.
            if (!Environment.IsLibrary)
                Environment.Set("pbxproj.swiftBridgingHeader", "@(headerDirectory)/uSwiftBridging.h");
        }
    }
}
